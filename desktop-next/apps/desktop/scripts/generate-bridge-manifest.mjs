// Regenerates electron/vanta/surface-manifest.ts: every member the Hermes preload exposes on
// `window.hermesDesktop`, with the kind of stand-in the Vanta bridge gives an unimplemented one.
// Run from apps/desktop:  node scripts/generate-bridge-manifest.mjs
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const ts = require('typescript')
const here = path.dirname(fileURLToPath(import.meta.url))
const source = path.join(here, '../electron/preload.ts')
const target = path.join(here, '../electron/vanta/surface-manifest.ts')
const file = ts.createSourceFile(source, readFileSync(source, 'utf8'), ts.ScriptTarget.Latest, true)

// event: ipcRenderer.on subscription, returns an unsubscribe. send: fire-and-forget. async: invoke.
// flag: a boolean fact computed at load. null: a nullable fact. omit: optional in the HermesDesktop type
// (platform-specific native gestures) and simply absent here.
const OMIT = new Set(['screenshot', 'hudModifier'])

function kindOf(initializer, text, name) {
  if (OMIT.has(name)) {
    return 'omit'
  }

  if (ts.isObjectLiteralExpression(initializer)) {
    return walk(initializer)
  }

  if (ts.isArrowFunction(initializer) || ts.isFunctionExpression(initializer)) {
    if (text.includes('ipcRenderer.on(')) return 'event'
    if (text.includes('ipcRenderer.invoke(')) return 'async'
    if (text.includes('ipcRenderer.send(') || text.includes('ipcRenderer.sendSync(')) return 'send'
    return 'send'
  }

  if (/=== true|=== false|!== false|!== true|!!|Boolean\(|customWindowControlsEnabled|^hud\w*$/.test(text))
    return 'flag'
  if (text === 'null' || /\?\?\s*null|\?\s*[^:]+:\s*null/.test(text)) return 'null'
  return 'null'
}

function walk(object) {
  const out = {}
  for (const property of object.properties) {
    const name = property.name?.getText().replace(/['"]/g, '')
    if (!name || !property.initializer) continue
    out[name] = kindOf(property.initializer, property.initializer.getText(), name)
  }
  return out
}

let manifest
const visit = node => {
  if (ts.isCallExpression(node) && node.expression.getText() === 'contextBridge.exposeInMainWorld') {
    manifest = walk(node.arguments[1])
  }
  ts.forEachChild(node, visit)
}
visit(file)

// One line per top-level member; nested namespaces stay on that line (prettier wraps the long ones).
const key = name => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`)
const inline = value =>
  `{ ${Object.entries(value)
    .map(([name, entry]) => `${key(name)}: ${typeof entry === 'string' ? `'${entry}'` : inline(entry)}`)
    .join(', ')} }`
const render = value =>
  Object.entries(value)
    .map(([name, entry]) => `  ${key(name)}: ${typeof entry === 'string' ? `'${entry}'` : inline(entry)}`)
    .join(',\n')

writeFileSync(
  target,
  `// GENERATED by scripts/generate-bridge-manifest.mjs from electron/preload.ts. Do not edit by hand.
// The complete Hermes bridge surface and how the Vanta bridge stands in for a member it does not implement.

export type StubKind = 'async' | 'event' | 'flag' | 'null' | 'omit' | 'send'
export type SurfaceManifest = { [member: string]: StubKind | SurfaceManifest }

export const SURFACE_MANIFEST: SurfaceManifest = {
${render(manifest)}
}
`
)
console.log(`wrote ${path.relative(process.cwd(), target)}`)
